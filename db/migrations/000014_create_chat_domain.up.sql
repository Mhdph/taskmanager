-- Chat domain.
--
-- Three conversation kinds share one table:
--   project : exactly one per project; membership is mirrored from
--             project_members (plus explicitly added non-members such as
--             workspace admins).
--   dm      : exactly two members. "dm_key" is the canonical sorted user
--             pair, so a pair can never own two DM threads.
--   group   : free-form workspace conversation with a title.
--
-- Message ordering uses "seq", a database-generated identity column. It is
-- monotonic and immune to clock skew, and clients paginate on it instead of
-- timestamps. "client_message_id" makes sends idempotent: a retried request
-- with the same id returns the original row instead of duplicating it.

CREATE TABLE conversations (
    id UUID PRIMARY KEY,

    tenant_id TEXT NOT NULL,

    type TEXT NOT NULL
        CHECK (type IN ('project', 'dm', 'group')),

    project_id UUID
        REFERENCES projects (id)
        ON DELETE CASCADE,

    -- dm_key is NULL for non-DM conversations.
    dm_key TEXT,

    title TEXT NOT NULL DEFAULT '',

    created_by_user_id TEXT NOT NULL,

    -- Denormalized tail of the message stream, so the conversation list
    -- can sort and render a preview without scanning messages.
    last_message_seq BIGINT NOT NULL DEFAULT 0,
    last_message_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (
        (
            type = 'project'
            AND project_id IS NOT NULL
            AND dm_key IS NULL
        )
        OR (
            type = 'dm'
            AND project_id IS NULL
            AND dm_key IS NOT NULL
        )
        OR (
            type = 'group'
            AND project_id IS NULL
            AND dm_key IS NULL
        )
    )
);

-- One chat per project.
CREATE UNIQUE INDEX conversations_project_idx
    ON conversations (tenant_id, project_id)
    WHERE type = 'project';

-- One chat per user pair.
CREATE UNIQUE INDEX conversations_dm_idx
    ON conversations (tenant_id, dm_key)
    WHERE type = 'dm';

CREATE INDEX conversations_tenant_idx
    ON conversations (tenant_id);


CREATE TABLE conversation_members (
    conversation_id UUID NOT NULL
        REFERENCES conversations (id)
        ON DELETE CASCADE,

    tenant_id TEXT NOT NULL,

    user_id TEXT NOT NULL,

    role TEXT NOT NULL DEFAULT 'member'
        CHECK (role IN ('owner', 'member')),

    -- 'project' rows are managed by the project-membership sync and are
    -- pruned when the user leaves the project. 'manual' rows (DM members,
    -- group members, admins who opened a project chat) are managed
    -- explicitly and survive the sync.
    source TEXT NOT NULL DEFAULT 'manual'
        CHECK (source IN ('manual', 'project')),

    -- Read cursor: everything up to this sequence is considered read.
    -- Unread counts are COUNT(seq > last_read_seq), which stays O(1) for
    -- the reader regardless of conversation size.
    last_read_seq BIGINT NOT NULL DEFAULT 0
        CHECK (last_read_seq >= 0),

    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (conversation_id, user_id)
);

CREATE INDEX conversation_members_user_idx
    ON conversation_members (tenant_id, user_id);


CREATE TABLE messages (
    id UUID PRIMARY KEY,

    tenant_id TEXT NOT NULL,

    conversation_id UUID NOT NULL
        REFERENCES conversations (id)
        ON DELETE CASCADE,

    -- Monotonic ordering key. Generated by the database so concurrent
    -- writers cannot observe out-of-order commits: the sequence is
    -- assigned at INSERT time.
    seq BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY,

    kind TEXT NOT NULL DEFAULT 'user'
        CHECK (kind IN ('user', 'system')),

    -- NULL for system messages.
    author_user_id TEXT,

    body TEXT NOT NULL DEFAULT ''
        CHECK (char_length(body) <= 10000),

    -- Client-generated UUID for idempotent retries. NULL for system
    -- messages and older clients.
    client_message_id TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    edited_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,

    CHECK (kind <> 'user' OR author_user_id IS NOT NULL),

    -- Soft deletes keep the tombstone in the stream (so ordering and
    -- pagination stay stable) but never keep the content.
    CHECK (deleted_at IS NULL OR body = '')
);

CREATE INDEX messages_conversation_seq_idx
    ON messages (conversation_id, seq DESC);

-- Idempotency key: one row per (author, client message id) per tenant.
CREATE UNIQUE INDEX messages_client_message_idx
    ON messages (tenant_id, author_user_id, client_message_id)
    WHERE kind = 'user' AND client_message_id IS NOT NULL;

CREATE INDEX messages_tenant_author_idx
    ON messages (tenant_id, author_user_id);
